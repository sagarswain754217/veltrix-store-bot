    query = update.callback_query
    await query.answer()

    user_id = query.from_user.id
    product = context.user_data.get('selected_product')
    qty = context.user_data.get('quantity')
    total = context.user_data.get('total_amount')

    if not product or not qty or total is None:
        await query.edit_message_text("❌ Session expired. Please start again from Shop.")
        return

    conn = get_db_connection()
    c = conn.cursor()

    # Check balance
    c.execute("SELECT balance FROM users WHERE user_id = ?", (user_id,))
    row = c.fetchone()
    balance = row['balance'] if row else 0.0

    if balance < total:
        conn.close()
        text = (
            f"❌ <b>Insufficient Balance</b>\n\n"
            f"Your balance: <b>{format_money(balance)}</b>\n"
            f"Required: <b>{format_money(total)}</b>\n\n"
            f"Please deposit first."
        )
        keyboard = [
            [InlineKeyboardButton("💰 Go to Wallet", callback_data="wallet")],
            [InlineKeyboardButton("🔙 Back", callback_data="shop")]
        ]
        await query.edit_message_text(text=text, reply_markup=InlineKeyboardMarkup(keyboard), parse_mode=ParseMode.HTML)
        return

    # Check available stock
    c.execute(
        "SELECT COUNT(*) FROM stock WHERE product_id = ? AND status = 'AVAILABLE'",
        (product['product_id'],)
    )
    available = c.fetchone()[0]
    if available < qty:
        conn.close()
        await query.edit_message_text("❌ Not enough stock left. Please try again.")
        return

    # Create unique Order ID
    order_id = generate_order_id()

    # Deduct balance
    c.execute(
        "UPDATE users SET balance = balance - ?, total_spent = total_spent + ?, total_orders = total_orders + 1 WHERE user_id = ?",
        (total, total, user_id)
    )

    # Create order
    c.execute('''
        INSERT INTO orders (order_id, user_id, product_id, quantity, total_amount, payment_method, status, created_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    ''', (order_id, user_id, product['product_id'], qty, total, "wallet", "APPROVED", get_current_time()))

    # Reserve stock
    c.execute('''
        SELECT stock_id, content FROM stock
        WHERE product_id = ? AND status = 'AVAILABLE'
        LIMIT ?
    ''', (product['product_id'], qty))
    stocks = c.fetchall()

    delivered_items = []
    for stock in stocks:
        c.execute('''
            UPDATE stock SET status = 'DELIVERED', reserved_by = ?, delivered_at = ?, order_id = ?
            WHERE stock_id = ?
        ''', (user_id, get_current_time(), order_id, stock['stock_id']))
        delivered_items.append(stock['content'])

    conn.commit()
    conn.close()

    # ========== DELIVERY LOGIC ==========
    if "YouTube" in product['name']:
        # Special message for YouTube Premium
        await send_youtube_instruction(context, order_id, user_id)
        await query.edit_message_text(
            f"✅ <b>Payment Successful!</b>\n\nPlease check the message below.",
            parse_mode=ParseMode.HTML
        )
    else:
        # Normal delivery for other products
        delivery_text = (
            f"✅ <b>Payment Successful!</b>\n\n"
            f"🆔 Order ID: <code>{order_id}</code>\n"
            f"{product['emoji']} <b>{product['name']}</b>\n"
            f"📦 Quantity: {qty}\n"
            f"💰 Paid: {format_money(total)} (from Wallet)\n\n"
            f"<b>Your Product(s):</b>\n\n"
        )
        for i, item in enumerate(delivered_items, 1):
            delivery_text += f"<b>#{i}</b>\n<code>{item}</code>\n\n"

        delivery_text += "⚠️ Keep this information safe!"

        keyboard = [
            [InlineKeyboardButton("📦 My Orders", callback_data="my_orders")],
            [InlineKeyboardButton("🏠 Main Menu", callback_data="main_menu")]
        ]
