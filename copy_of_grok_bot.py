def generate_order_id() -> str:
    """Generate unique Order ID: VTX-YYYYMMDD-XXXXXX"""
    date_part = datetime.now(timezone.utc).strftime("%Y%m%d")
    random_part = ''.join(random.choices(string.ascii_uppercase + string.digits, k=6))
