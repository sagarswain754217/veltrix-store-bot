async def handle_deposit_proof(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Handle TXID / Binance ref for deposits + Duplicate protection"""
    if not update.message or not update.message.text:
        return

    user_id = update.effective_user.id
    proof = update.message.text.strip()
    waiting_for = context.user_data.get('waiting_for')
    deposit_id = context.user_data.get('pending_deposit_id')

    if waiting_for not in ["deposit_txid", "deposit_binance_ref"] or not deposit_id:
        return

    if len(proof) < 8:
        await update.message.reply_text("❌ Invalid proof. Please send a valid TXID or reference.")
        return

    conn = get_db_connection()
    c = conn.cursor()

    # Check deposit ownership + status
    c.execute(
        "SELECT * FROM wallet_deposits WHERE deposit_id = ? AND user_id = ? AND status = 'PENDING'",
        (deposit_id, user_id)
    )
    deposit = c.fetchone()

    if not deposit:
        conn.close()
        await update.message.reply_text("❌ Deposit not found or already processed.")
        context.user_data.clear()
        return

    # ===== DUPLICATE PROTECTION =====
    if waiting_for == "deposit_txid":
        # Check in both orders and deposits
        c.execute("SELECT deposit_id FROM wallet_deposits WHERE txid = ? AND status != 'REJECTED'", (proof,))
        if c.fetchone():
            conn.close()
            await update.message.reply_text(
                "❌ <b>Duplicate TXID detected!</b>\nThis TXID has already been used.",
                parse_mode=ParseMode.HTML
            )
            return
        c.execute("SELECT order_id FROM orders WHERE txid = ? AND status != 'CANCELLED'", (proof,))
        if c.fetchone():
            conn.close()
            await update.message.reply_text(
                "❌ <b>Duplicate TXID detected!</b>\nThis TXID has already been used in an order.",
                parse_mode=ParseMode.HTML
            )
            return
    else:
        c.execute("SELECT deposit_id FROM wallet_deposits WHERE binance_ref = ? AND status != 'REJECTED'", (proof,))
        if c.fetchone():
            conn.close()
            await update.message.reply_text(
                "❌ <b>Duplicate Binance Reference detected!</b>",
                parse_mode=ParseMode.HTML
            )
            return
        c.execute("SELECT order_id FROM orders WHERE binance_ref = ? AND status != 'CANCELLED'", (proof,))
        if c.fetchone():
            conn.close()
            await update.message.reply_text(
                "❌ <b>Duplicate Binance Reference detected!</b>",
                parse_mode=ParseMode.HTML
            )
            return

    # Save proof
    if waiting_for == "deposit_txid":
        c.execute("UPDATE wallet_deposits SET txid = ? WHERE deposit_id = ?", (proof, deposit_id))
        proof_type = "TXID"
    else:
        c.execute("UPDATE wallet_deposits SET binance_ref = ? WHERE deposit_id = ?", (proof, deposit_id))
        proof_type = "Binance Reference"

    conn.commit()
    conn.close()

    context.user_data.clear()

    await update.message.reply_text(
        f"✅ <b>{proof_type} submitted successfully!</b>\n\n"
        f"🆔 Deposit ID: <code>{deposit_id}</code>\n"
        f"📄 {proof_type}: <code>{proof}</code>\n\n"
        f"Status: <b>Pending Admin Approval</b>\n"
        f"Your balance will be credited after approval.",
        parse_mode=ParseMode.HTML
    )

    # Notify Admin
    try:
        admin_text = (
            f"💵 <b>New Wallet Deposit Pending</b>\n\n"
            f"🆔 Deposit ID: <code>{deposit_id}</code>\n"
            f"👤 User ID: <code>{user_id}</code>\n"
            f"💰 Amount: <b>{format_money(deposit['amount'])}</b>\n"
            f"💳 Method: <b>{deposit['payment_method'].upper()}</b>\n"
            f"📄 {proof_type}: <code>{proof}</code>\n\n"
            f"➡️ Go to /admin → Wallet Deposits"
        )
        await context.bot.send_message(chat_id=ADMIN_ID, text=admin_text, parse_mode=ParseMode.HTML)
    except Exception as e:
        logger.error(f"Admin notify error: {e}")


