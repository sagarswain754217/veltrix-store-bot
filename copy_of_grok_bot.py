async def handle_payment_proof(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Receive TXID or Binance reference + Full Duplicate Protection"""
    if not update.message or not update.message.text:
        return

    user_id = update.effective_user.id
    proof = update.message.text.strip()
    waiting_for = context.user_data.get('waiting_for')
    order_id = context.user_data.get('pending_order_id')

    if not waiting_for or not order_id:
        return

    # Basic length validation
    if len(proof) < 8:
        await update.message.reply_text(
            "❌ Invalid payment proof.\nPlease send a valid TXID or Binance reference."
        )
        return

    conn = get_db_connection()
    c = conn.cursor()

    # 1. Check if order exists, belongs to user, and is still PENDING
    c.execute(
        "SELECT * FROM orders WHERE order_id = ? AND user_id = ? AND status = 'PENDING'",
        (order_id, user_id)
    )
    order = c.fetchone()

    if not order:
        conn.close()
        await update.message.reply_text("❌ Order not found or already processed.")
        context.user_data.clear()
        return

    # 2. DUPLICATE PROTECTION
    if waiting_for == "txid":
        c.execute(
            "SELECT order_id FROM orders WHERE txid = ? AND status != 'CANCELLED'",
            (proof,)
        )
        existing = c.fetchone()
        if existing:
            conn.close()
            await update.message.reply_text(
                f"❌ <b>Duplicate TXID Detected!</b>\n\n"
                f"This Transaction ID has already been used.\n"
                f"You cannot use the same TXID for multiple orders.\n\n"
                f"Contact support if you believe this is an error: {SUPPORT_USERNAME}",
                parse_mode=ParseMode.HTML
            )
            return
    else:  # binance_ref
        c.execute(
            "SELECT order_id FROM orders WHERE binance_ref = ? AND status != 'CANCELLED'",
            (proof,)
        )
        existing = c.fetchone()
        if existing:
            conn.close()
            await update.message.reply_text(
                f"❌ <b>Duplicate Binance Reference Detected!</b>\n\n"
                f"This payment reference has already been used.\n"
                f"You cannot reuse the same reference.\n\n"
                f"Contact support if needed: {SUPPORT_USERNAME}",
                parse_mode=ParseMode.HTML
            )
            return

    # 3. Save the proof
    if waiting_for == "txid":
        c.execute("UPDATE orders SET txid = ? WHERE order_id = ?", (proof, order_id))
        proof_type = "TXID"
    else:
        c.execute("UPDATE orders SET binance_ref = ? WHERE order_id = ?", (proof, order_id))
        proof_type = "Binance Reference"

    conn.commit()
    conn.close()

    # Clear state
    context.user_data.clear()

    # Confirm to user
    await update.message.reply_text(
        f"✅ <b>{proof_type} Submitted Successfully!</b>\n\n"
        f"🆔 Order ID: <code>{order_id}</code>\n"
        f"📄 {proof_type}: <code>{proof}</code>\n\n"
        f"Status: <b>Pending Admin Approval</b>\n"
        f"You will receive the product automatically once approved.",
        parse_mode=ParseMode.HTML
    )

    # 4. Notify Admin
    try:
        admin_text = (
            f"🔔 <b>New Payment Pending Approval</b>\n\n"
            f"🆔 Order ID: <code>{order_id}</code>\n"
            f"👤 User ID: <code>{user_id}</code>\n"
            f"💰 Amount: <b>{format_money(order['total_amount'])}</b>\n"
            f"💳 Method: <b>{order['payment_method'].upper()}</b>\n"
            f"📄 {proof_type}: <code>{proof}</code>\n\n"
            f"➡️ Go to /admin → Direct Payments"
        )
        await context.bot.send_message(
            chat_id=ADMIN_ID,
            text=admin_text,
            parse_mode=ParseMode.HTML
        )
    except Exception as e:
        logger.error(f"Failed to notify admin: {e}")


