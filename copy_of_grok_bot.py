async def handle_stock_file(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Process uploaded TXT file"""
    if not update.message or not update.message.document:
        return

    if context.user_data.get('waiting_for') != "stock_file":
        return

    if not is_admin(update.effective_user.id):
        return

    document = update.message.document

    if not document.file_name.lower().endswith(".txt"):
        await update.message.reply_text("❌ Please upload a .txt file only.")
        return

    product_id = context.user_data.get('add_stock_product_id')
    if not product_id:
        await update.message.reply_text("❌ Session expired.")
        return

    # Download file
    file = await context.bot.get_file(document.file_id)
    file_content = await file.download_as_bytearray()
    content = file_content.decode("utf-8", errors="ignore")

    lines = [line.strip() for line in content.splitlines() if line.strip()]

    if not lines:
        await update.message.reply_text("❌ File is empty.")
        return

    conn = get_db_connection()
    c = conn.cursor()

    added = 0
    for line in lines:
        c.execute(
            "INSERT INTO stock (product_id, content, status) VALUES (?, ?, 'AVAILABLE')",
            (product_id, line)
        )
        added += 1

    c.execute(
        "SELECT COUNT(*) FROM stock WHERE product_id = ? AND status = 'AVAILABLE'",
        (product_id,)
    )
    total_available = c.fetchone()[0]

    c.execute("SELECT name, emoji FROM products WHERE product_id = ?", (product_id,))
    product = c.fetchone()

    conn.commit()
    conn.close()

    context.user_data.clear()

    await update.message.reply_text(
        f"✅ <b>Stock Added Successfully!</b>\n\n"
        f"Product: {product['emoji']} <b>{product['name']}</b>\n"
        f"➕ Added: <b>{added}</b>\n"
        f"📦 Total Available now: <b>{total_available}</b>",
        parse_mode=ParseMode.HTML
    )


