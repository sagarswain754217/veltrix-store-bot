DB_NAME = "veltrix_store.db"

def init_db():
    conn = sqlite3.connect(DB_NAME)
    c = conn.cursor()

    # Users table
    c.execute('''
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            username TEXT,
            full_name TEXT,
            balance REAL DEFAULT 0.0,
            total_spent REAL DEFAULT 0.0,
            total_orders INTEGER DEFAULT 0,
            joined_at TEXT,
            is_banned INTEGER DEFAULT 0,
            last_active TEXT
        )
    ''')

    # Products table
    c.execute('''
        CREATE TABLE IF NOT EXISTS products (
            product_id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            duration TEXT,
            price REAL NOT NULL,
            emoji TEXT,
            is_active INTEGER DEFAULT 1
        )
    ''')

    # Stock table (each line = one account)
    c.execute('''
        CREATE TABLE IF NOT EXISTS stock (
            stock_id INTEGER PRIMARY KEY AUTOINCREMENT,
            product_id INTEGER,
            content TEXT NOT NULL,
            status TEXT DEFAULT 'AVAILABLE',  -- AVAILABLE, RESERVED, DELIVERED
            reserved_by INTEGER,
            reserved_at TEXT,
            delivered_at TEXT,
            order_id TEXT,
            FOREIGN KEY (product_id) REFERENCES products(product_id)
        )
    ''')

    # Orders table
    c.execute('''
        CREATE TABLE IF NOT EXISTS orders (
            order_id TEXT PRIMARY KEY,
            user_id INTEGER,
            product_id INTEGER,
            quantity INTEGER,
            total_amount REAL,
            payment_method TEXT,          -- wallet, bep20, binance
            status TEXT DEFAULT 'PENDING', -- PENDING, APPROVED, REJECTED, DELIVERED, CANCELLED
            txid TEXT,
            binance_ref TEXT,
            created_at TEXT,
            approved_at TEXT,
            delivered_at TEXT,
            admin_note TEXT,
            FOREIGN KEY (user_id) REFERENCES users(user_id),
            FOREIGN KEY (product_id) REFERENCES products(product_id)
        )
    ''')

    # Wallet deposits table
    c.execute('''
        CREATE TABLE IF NOT EXISTS wallet_deposits (
            deposit_id TEXT PRIMARY KEY,
            user_id INTEGER,
            amount REAL,
            payment_method TEXT,          -- bep20, binance
            status TEXT DEFAULT 'PENDING', -- PENDING, APPROVED, REJECTED
            txid TEXT,
            binance_ref TEXT,
            created_at TEXT,
            approved_at TEXT,
            admin_note TEXT,
            FOREIGN KEY (user_id) REFERENCES users(user_id)
        )
    ''')

    # Admin logs
    c.execute('''
        CREATE TABLE IF NOT EXISTS admin_logs (
            log_id INTEGER PRIMARY KEY AUTOINCREMENT,
            admin_id INTEGER,
            action TEXT,
            details TEXT,
            created_at TEXT
        )
    ''')

    # Settings table (for future use)
    c.execute('''
        CREATE TABLE IF NOT EXISTS settings (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    ''')

    conn.commit()

    # Insert default products if they don't exist
    c.execute("SELECT COUNT(*) FROM products")
    if c.fetchone()[0] == 0:
        products = [
            ("Netflix 4K UHD", "1 Month", 1.00, "📺"),
            ("Spotify Premium", "2 Months", 0.60, "🎵"),
            ("YouTube Premium Invite", "1 Month", 0.30, "▶️"),
            ("Gemini Pro", "18 Months", 0.50, "✨"),
        ]
        c.executemany(
            "INSERT INTO products (name, duration, price, emoji) VALUES (?, ?, ?, ?)",
            products
        )
        conn.commit()
        print("✅ Default products inserted successfully")

    conn.close()
    print("✅ Database initialized successfully!")
    print("Tables created: users, products, stock, orders, wallet_deposits, admin_logs, settings")

