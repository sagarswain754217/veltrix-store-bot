async def check_membership_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Handle the Check Membership button"""
    query = update.callback_query
    await query.answer()

    user_id = query.from_user.id
    is_member = await check_membership(user_id, context)

    if is_member:
        # Register / update user in database
        conn = get_db_connection()
        c = conn.cursor()
        c.execute("SELECT user_id FROM users WHERE user_id = ?", (user_id,))
        if not c.fetchone():
            c.execute(
                "INSERT INTO users (user_id, username, full_name, joined_at, last_active) VALUES (?, ?, ?, ?, ?)",
                (
                    user_id,
                    query.from_user.username,
                    query.from_user.full_name,
                    get_current_time(),
                    get_current_time()
                )
            )
        else:
            c.execute(
                "UPDATE users SET username = ?, full_name = ?, last_active = ? WHERE user_id = ?",
                (query.from_user.username, query.from_user.full_name, get_current_time(), user_id)
            )
        conn.commit()
